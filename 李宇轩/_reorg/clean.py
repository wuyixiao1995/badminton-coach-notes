def fix_text(t):
    t = t.replace("求","球")
    for a,b in repl:
        t = t.replace(a,b)
    return t

def clean(t):
    t = fix_text(t)
    for fw in ["呃","嗯","那个","诶","哎","啊","吓","对吧","的话"]:
        t = t.replace(fw,"")
    t = re.sub(r'[A-Za-z]{1,5}', '', t)
    t = re.sub(r'[ \t]+', '', t)
    # 按句切分
    sents = re.split(r'(?<=。|！|？)', t)
    sents = [s.strip() for s in sents if s and not re.fullmatch(r'[。！？，、；；\s]+', s)]
    paras=[]; buf=[]
    for s in sents:
        buf.append(s)
        if len(buf)>=4:
            paras.append("".join(buf)); buf=[]
    if buf: paras.append("".join(buf))
    return "\n\n".join(paras)

for fn in files:
    with open(os.path.join(chunk_dir, fn), encoding="utf-8") as f:
        raw = f.read()
    body = clean(raw)
    title = fn[:-4]
    md = "# " + title + "\n\n" + body + "\n"
    out_path = os.path.join(out_dir, title + ".md")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(md)
    print("written:", title, len(md))
